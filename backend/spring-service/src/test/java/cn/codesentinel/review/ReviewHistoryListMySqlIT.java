package cn.codesentinel.review;

import cn.codesentinel.task.PublishStatus;
import cn.codesentinel.task.ReviewReport;
import cn.codesentinel.task.ReviewReportRepository;
import cn.codesentinel.task.ReviewTask;
import cn.codesentinel.task.ReviewTaskRepository;
import cn.codesentinel.task.TaskStatus;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.AutoConfigureTestDatabase;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.testcontainers.containers.MySQLContainer;

import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.concurrent.atomic.AtomicLong;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Real-MySQL integration test of the Phase 11.2.2-A Dashboard list query.
 *
 * <p>The test schema is generated by Hibernate ({@code create-drop}) so the
 * fixture contains {@code review_task}, which the Phase 10 history fixture
 * intentionally omits. The list query and its mapping are executed against
 * MySQL, including the fixed {@code created_at DESC, id DESC} ordering.
 */
@DataJpaTest(properties = {
        "spring.jpa.hibernate.ddl-auto=create-drop"
})
@AutoConfigureTestDatabase(
        replace = AutoConfigureTestDatabase.Replace.NONE)
@Import(ReviewHistoryListService.class)
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@Tag("mysql-it")
class ReviewHistoryListMySqlIT {

    private static final AtomicLong SEQUENCE = new AtomicLong(1);

    private static final MySQLContainer<?> MYSQL =
            new MySQLContainer<>("mysql:8.0.46")
                    .withDatabaseName("codesentinel_dashboard_it")
                    .withUsername("it")
                    .withPassword("it");

    static {
        MYSQL.start();
    }

    @DynamicPropertySource
    static void datasourceProperties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", MYSQL::getJdbcUrl);
        registry.add("spring.datasource.username", MYSQL::getUsername);
        registry.add("spring.datasource.password", MYSQL::getPassword);
        registry.add("spring.datasource.driver-class-name",
                () -> "com.mysql.cj.jdbc.Driver");
        registry.add("spring.jpa.hibernate.ddl-auto", () -> "create-drop");
    }

    @Autowired
    private ReviewTaskRepository taskRepository;
    @Autowired
    private ReviewReportRepository reportRepository;
    @Autowired
    private ReviewHistoryListService listService;
    @Autowired
    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void cleanDatabase() {
        reportRepository.deleteAllInBatch();
        taskRepository.deleteAllInBatch();
    }

    @Test
    void shouldFilterByTaskFieldsPublishStatusAndAiStatus() {
        ReviewTask first = task("alpha", "r1", 1, TaskStatus.COMPLETED);
        ReviewTask second = task("alpha", "r1", 2, TaskStatus.COMPLETED);
        ReviewTask third = task("alpha", "r1", 1, TaskStatus.FAILED);
        ReviewTask fourth = task("beta", "r2", 1, TaskStatus.COMPLETED);
        report(first, "COMPLETED", PublishStatus.PUBLISHED,
                LocalDateTime.of(2026, 1, 3, 0, 0));
        report(second, "DEGRADED", PublishStatus.PENDING,
                LocalDateTime.of(2026, 1, 2, 0, 0));
        report(third, "COMPLETED", PublishStatus.FAILED,
                LocalDateTime.of(2026, 1, 1, 0, 0));
        report(fourth, "COMPLETED", PublishStatus.PUBLISHED,
                LocalDateTime.of(2026, 1, 4, 0, 0));

        ReviewHistoryFilter filter = new ReviewHistoryFilter(
                "alpha", "r1", 1, TaskStatus.COMPLETED,
                PublishStatus.PUBLISHED, "COMPLETED", null, null);

        ReviewPageResponse<ReviewReportResponse> response =
                listService.search(filter, 1, 20);

        assertEquals(1, response.totalItems());
        assertEquals(1, response.totalPages());
        assertFalse(response.hasNext());
        assertEquals(first.getId(),
                response.items().get(0).taskId());
        assertEquals("alpha", response.items().get(0).owner());
        assertEquals("r1", response.items().get(0).repo());
    }

    @Test
    void shouldApplyInclusiveCreatedAtBounds() {
        LocalDateTime first = LocalDateTime.of(2026, 1, 1, 0, 0);
        LocalDateTime second = LocalDateTime.of(2026, 1, 15, 12, 0);
        LocalDateTime third = LocalDateTime.of(2026, 2, 1, 0, 0);
        report(task("owner", "repo", 1, TaskStatus.COMPLETED),
                "COMPLETED", PublishStatus.PUBLISHED, first);
        report(task("owner", "repo", 2, TaskStatus.COMPLETED),
                "COMPLETED", PublishStatus.PUBLISHED, second);
        report(task("owner", "repo", 3, TaskStatus.COMPLETED),
                "COMPLETED", PublishStatus.PUBLISHED, third);

        ReviewPageResponse<ReviewReportResponse> inclusive =
                listService.search(new ReviewHistoryFilter(null, null, null,
                        null, null, null, first, third), 1, 20);
        assertEquals(3, inclusive.totalItems());

        ReviewPageResponse<ReviewReportResponse> afterFirst =
                listService.search(new ReviewHistoryFilter(null, null, null,
                        null, null, null,
                        first.plus(1, ChronoUnit.MICROS), null), 1, 20);
        assertEquals(2, afterFirst.totalItems());

        ReviewPageResponse<ReviewReportResponse> beforeThird =
                listService.search(new ReviewHistoryFilter(null, null, null,
                        null, null, null, null,
                        third.minus(1, ChronoUnit.MICROS)), 1, 20);
        assertEquals(2, beforeThird.totalItems());
    }

    @Test
    void shouldPaginateWithStableCreatedAtAndIdDescendingSort() {
        LocalDateTime newest = LocalDateTime.of(2026, 3, 1, 10, 0);
        ReviewTask first = task("owner", "repo", 1, TaskStatus.COMPLETED);
        ReviewTask second = task("owner", "repo", 2, TaskStatus.COMPLETED);
        ReviewTask third = task("owner", "repo", 3, TaskStatus.COMPLETED);
        ReviewTask fourth = task("owner", "repo", 4, TaskStatus.COMPLETED);
        ReviewTask fifth = task("owner", "repo", 5, TaskStatus.COMPLETED);
        report(first, "COMPLETED", PublishStatus.PUBLISHED, newest);
        report(second, "COMPLETED", PublishStatus.PUBLISHED, newest);
        report(third, "COMPLETED", PublishStatus.PUBLISHED, newest);
        report(fourth, "COMPLETED", PublishStatus.PUBLISHED,
                LocalDateTime.of(2026, 2, 1, 0, 0));
        report(fifth, "COMPLETED", PublishStatus.PUBLISHED,
                LocalDateTime.of(2026, 1, 1, 0, 0));

        ReviewPageResponse<ReviewReportResponse> page1 =
                listService.search(emptyFilter(), 1, 2);
        ReviewPageResponse<ReviewReportResponse> page2 =
                listService.search(emptyFilter(), 2, 2);
        ReviewPageResponse<ReviewReportResponse> page3 =
                listService.search(emptyFilter(), 3, 2);

        assertEquals(5, page1.totalItems());
        assertEquals(3, page1.totalPages());
        assertEquals(List.of(third.getId(), second.getId()),
                taskIds(page1));
        assertEquals(List.of(first.getId(), fourth.getId()),
                taskIds(page2));
        assertEquals(List.of(fifth.getId()), taskIds(page3));
        assertTrue(page1.hasNext());
        assertTrue(page2.hasNext());
        assertFalse(page3.hasNext());
    }

    @Test
    void shouldMapRealReportFields() {
        ReviewTask task = task("owner", "repo", 42, TaskStatus.COMPLETED);
        LocalDateTime publishedAt = LocalDateTime.of(2026, 1, 2, 3, 4, 5);
        ReviewReport report = report(task, "DEGRADED", PublishStatus.PARTIAL,
                LocalDateTime.of(2026, 1, 2, 3, 0), publishedAt, 900L, 2, 1);
        LocalDateTime updatedAt = LocalDateTime.of(2026, 1, 2, 3, 4, 6);
        jdbcTemplate.update(
                "UPDATE review_report SET updated_at = ? WHERE id = ?",
                Timestamp.valueOf(updatedAt), report.getId());

        ReviewPageResponse<ReviewReportResponse> response =
                listService.search(emptyFilter(), 1, 20);

        assertEquals(1, response.totalItems());
        ReviewReportResponse item = response.items().get(0);
        assertEquals(task.getId(), item.taskId());
        assertEquals("owner", item.owner());
        assertEquals("repo", item.repo());
        assertEquals(42, item.prNumber());
        assertEquals(task.getCommitSha(), item.commitSha());
        assertEquals("COMPLETED", item.taskStatus());
        assertEquals("DEGRADED", item.aiStatus());
        assertEquals("PARTIAL", item.publishStatus());
        assertEquals(2, item.findingCount());
        assertEquals(1, item.publishedCommentCount());
        assertEquals(900L, item.summaryCommentId());
        assertEquals(publishedAt, item.publishedAt());
        assertEquals(LocalDateTime.of(2026, 1, 2, 3, 0), item.createdAt());
        assertEquals(updatedAt, item.updatedAt());
    }

    @Test
    void shouldExcludeTasksWithoutAStructuredReport() {
        task("owner", "repo", 1, TaskStatus.COMPLETED);

        ReviewPageResponse<ReviewReportResponse> response =
                listService.search(emptyFilter(), 1, 20);

        assertTrue(response.items().isEmpty());
        assertEquals(0, response.totalItems());
        assertEquals(0, response.totalPages());
        assertFalse(response.hasNext());
    }

    private ReviewTask task(String owner, String repo, int prNumber,
                            TaskStatus status) {
        ReviewTask task = new ReviewTask(owner, repo, prNumber,
                String.format("%040d", SEQUENCE.getAndIncrement()));
        task.setStatus(status);
        return taskRepository.saveAndFlush(task);
    }

    private ReviewReport report(ReviewTask task, String aiStatus,
                                PublishStatus publishStatus,
                                LocalDateTime createdAt) {
        return report(task, aiStatus, publishStatus, createdAt, null, null, 0,
                0);
    }

    private ReviewReport report(ReviewTask task, String aiStatus,
                                PublishStatus publishStatus,
                                LocalDateTime createdAt,
                                LocalDateTime publishedAt,
                                Long summaryCommentId, int findingCount,
                                int commentCount) {
        ReviewReport report = reportRepository.saveAndFlush(new ReviewReport(
                task.getId(), task.getCommitSha(), aiStatus, publishStatus,
                findingCount, commentCount, summaryCommentId, publishedAt));
        jdbcTemplate.update(
                "UPDATE review_report SET created_at = ? WHERE id = ?",
                Timestamp.valueOf(createdAt), report.getId());
        return report;
    }

    private static List<Long> taskIds(
            ReviewPageResponse<ReviewReportResponse> response) {
        return response.items().stream()
                .map(ReviewReportResponse::taskId)
                .toList();
    }

    private static ReviewHistoryFilter emptyFilter() {
        return new ReviewHistoryFilter(null, null, null, null, null, null,
                null, null);
    }
}
